# Let's parse translations.js carefully and insert entries into SI and TA dicts
si_entries_str = ",\n".join([f'        {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in crafts_translations_SI.items()])
ta_entries_str = ",\n".join([f'        {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in crafts_translations_TA.items()])

# Find SI ending: right before "    },\n    TA: {"
si_split = code.split("    },\n    TA: {")
if len(si_split) == 2:
    new_code = si_split[0] + ",\n" + si_entries_str + "\n    },\n    TA: {" + si_split[1]
    
    # Find TA ending: right before the last "    }\n};" or "    }\n};\n"
    ta_split = new_code.rsplit("    }\n};", 1)
    if len(ta_split) == 2:
        final_code = ta_split[0] + ",\n" + ta_entries_str + "\n    }\n};" + ta_split[1]
        with open('resources/js/translations.js', 'w', encoding='utf-8') as f:
            f.write(final_code)
        print("Successfully updated resources/js/translations.js with crafts translations!")
    else:
        print("Failed to find TA ending")
else:
    print("Failed to find SI split")
